/**
 * El departamento y la ciudad con los que llega la ficha en blanco.
 *
 * La oficina presta donde está, así que la mayoría de los clientes viven en el
 * mismo sitio: dejarlo puesto ahorra dos toques por cliente y evita el que se
 * guarda sin ciudad porque nadie bajó a escogerla.
 */
export const CO_DEFAULT_STATE = "Magdalena";
export const CO_DEFAULT_CITY = "Santa Marta";

/** Los municipios de un departamento, o ninguno si el nombre no es de aquí. */
export function citiesOf(state: string | null | undefined): readonly string[] {
  if (!state) return [];
  return CO_DIVISIONS.find((division) => division.name === state)?.cities ?? [];
}
